  /// Language used by the context-free helpers below.
  /// Kept in sync by SettingsProvider whenever the language changes.
  static String currentLanguage = 'en';

  static String get(String key, String languageCode) {
    final lang = (languageCode == 'km') ? 'km' : 'en';
    return _values[lang]?[key] ?? _values['en']?[key] ?? key;
  }

  /// Context-free translation. Placeholders {0}, {1}, ... are replaced
  /// with [args] in order.
  static String t(String key, [List<Object?> args = const []]) {
    var text = get(key, currentLanguage);
    for (var i = 0; i < args.length; i++) {
      text = text.replaceAll('{$i}', '${args[i]}');
    }
    return text;
  }

  /// Localized label for a canonical English value that is stored or
  /// compared in code (categories, report periods). Unknown values are
  /// returned unchanged.
  static String label(String canonical) {
    final key = 'val_$canonical';
    final lang = (currentLanguage == 'km') ? 'km' : 'en';
    return _values[lang]?[key] ?? _values['en']?[key] ?? canonical;
  }
}

// Extension to easily call context.tr('key') from any widget
extension TranslationExtension on BuildContext {
  String tr(String key, [List<Object?> args = const []]) {
    try {
      final settings = Provider.of<SettingsProvider>(this, listen: true);
      var text = AppTranslations.get(key, settings.language);
      for (var i = 0; i < args.length; i++) {
        text = text.replaceAll('{$i}', '${args[i]}');
      }
      return text;
    } catch (_) {
      return AppTranslations.get(key, 'en');
    }
  }

  // Non-listening version for callbacks / event handlers
  String trRead(String key) {
    try {
      final settings = Provider.of<SettingsProvider>(this, listen: false);
      return AppTranslations.get(key, settings.language);
    } catch (_) {
      return AppTranslations.get(key, 'en');
    }
  }
}
